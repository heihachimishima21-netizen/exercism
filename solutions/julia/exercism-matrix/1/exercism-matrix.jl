function frown!(E)
    E[7:9, :] = E[9:-1:7, :]
    E
end

function frown(E)
    f = copy(E)
    f[7:9, :] = f[9:-1:7, :]
    f
end

function stickerwall(E)
    vcat(hcat(E, frown(E)), ones(1, 36), hcat(frown(E), E))
end

function colpixelcount(E)
    sum(E; dims=1) .* E
end

function render(E)
   join([join((x -> x == 0 ? ' ' : 'X').(row)) for row in eachrow(E)], '\n')
end